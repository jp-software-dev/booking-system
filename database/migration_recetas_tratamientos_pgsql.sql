ALTER TABLE usuarios DROP CONSTRAINT IF EXISTS usuarios_rol_check;
ALTER TABLE usuarios ADD CONSTRAINT usuarios_rol_check CHECK (rol IN ('admin', 'recepcion', 'doctor'));
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS id_doctor INTEGER UNIQUE REFERENCES doctores (id_doctor) ON DELETE CASCADE;

CREATE TABLE IF NOT EXISTS recetas (
    id_receta     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente   INTEGER NOT NULL REFERENCES pacientes (id_paciente) ON DELETE CASCADE,
    id_doctor     INTEGER NOT NULL REFERENCES doctores (id_doctor) ON DELETE CASCADE,
    id_cita       INTEGER REFERENCES citas (id_cita) ON DELETE SET NULL,
    diagnostico   VARCHAR(255) NOT NULL,
    indicaciones  TEXT,
    fecha_emision TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_recetas_paciente ON recetas (id_paciente, fecha_emision);
CREATE INDEX IF NOT EXISTS idx_recetas_doctor ON recetas (id_doctor, fecha_emision);

CREATE TABLE IF NOT EXISTS tratamientos (
    id_tratamiento   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente      INTEGER NOT NULL REFERENCES pacientes (id_paciente) ON DELETE CASCADE,
    id_receta        INTEGER REFERENCES recetas (id_receta) ON DELETE CASCADE,
    origen           VARCHAR(10) NOT NULL CHECK (origen IN ('doctor', 'paciente')),
    medicamento      VARCHAR(120) NOT NULL,
    dosis            VARCHAR(120) NOT NULL,
    frecuencia_horas SMALLINT NOT NULL,
    duracion_dias    SMALLINT NOT NULL,
    fecha_inicio     TIMESTAMP NOT NULL,
    fecha_fin        TIMESTAMP NOT NULL,
    notas            VARCHAR(255),
    estado           VARCHAR(10) NOT NULL DEFAULT 'Activo' CHECK (estado IN ('Activo', 'Pausado', 'Cancelado')),
    creado_en        TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tratamientos_paciente ON tratamientos (id_paciente, estado);
CREATE INDEX IF NOT EXISTS idx_tratamientos_receta ON tratamientos (id_receta);

CREATE TABLE IF NOT EXISTS tomas (
    id_toma        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tratamiento INTEGER NOT NULL REFERENCES tratamientos (id_tratamiento) ON DELETE CASCADE,
    programada_en  TIMESTAMP NOT NULL,
    estado         VARCHAR(10) NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente', 'Tomada', 'Omitida')),
    registrada_en  TIMESTAMP,
    notificada_en  TIMESTAMP,
    UNIQUE (id_tratamiento, programada_en)
);
CREATE INDEX IF NOT EXISTS idx_tomas_aviso ON tomas (programada_en, notificada_en);

CREATE TABLE IF NOT EXISTS suscripciones_push (
    id_suscripcion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente    INTEGER NOT NULL REFERENCES pacientes (id_paciente) ON DELETE CASCADE,
    endpoint       TEXT NOT NULL,
    endpoint_hash  CHAR(64) NOT NULL UNIQUE,
    clave_p256dh   VARCHAR(255) NOT NULL,
    clave_auth     VARCHAR(100) NOT NULL,
    agente         VARCHAR(255),
    creada_en      TIMESTAMP NOT NULL,
    ultimo_envio   TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_suscripciones_paciente ON suscripciones_push (id_paciente);
